#!/usr/bin/env python3
"""Generate docs/mcp/tools.md from the tool registry of a running instance.

    python gen_tool_reference.py [--name dev] [--check]

Uses the instance started with `mcpctl.py start` (same --name), or launches a private one when
none is recorded. The page lists every tool exactly as tools/list reports it: description,
annotations and arguments from the JSON Schema. `--check` only compares and exits 1 when the
committed page is out of date.

The page is regenerated when tool groups are integrated; while groups are developed in parallel,
leave it alone (it would conflict) and document your tools in docs/mcp/tools-<group>.md.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from orca_mcp import McpClient, OrcaApp, REPO_ROOT, fresh_data_dir  # noqa: E402

TARGET = REPO_ROOT / "docs" / "mcp" / "tools.md"


def type_of(schema: dict, defs: dict) -> str:
    """A short, readable type for one argument."""
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f"[{name}](#shared-types)"
    if "enum" in schema:
        return " \\| ".join(f"`{json.dumps(value)}`" if not isinstance(value, str) else f"`{value}`" for value in schema["enum"])
    if "const" in schema:
        return f"`{json.dumps(schema['const'])}`"
    for combiner in ("oneOf", "anyOf"):
        if combiner in schema:
            return " or ".join(type_of(option, defs) for option in schema[combiner])
    kind = schema.get("type")
    if kind == "array":
        items = schema.get("items", {})
        inner = type_of(items, defs) if items else "any"
        return f"{inner}[]"
    if kind == "object":
        return "object"
    if isinstance(kind, list):
        return " or ".join(kind)
    return kind or "any"


def constraints(schema: dict) -> str:
    parts = []
    if "minimum" in schema and "maximum" in schema:
        parts.append(f"{schema['minimum']}..{schema['maximum']}")
    elif "minimum" in schema:
        parts.append(f">= {schema['minimum']}")
    elif "maximum" in schema:
        parts.append(f"<= {schema['maximum']}")
    if "exclusiveMinimum" in schema:
        parts.append(f"> {schema['exclusiveMinimum']}")
    if "minItems" in schema and schema.get("minItems") == schema.get("maxItems"):
        parts.append(f"{schema['minItems']} items")
    elif "minItems" in schema:
        parts.append(f"at least {schema['minItems']}")
    if "default" in schema:
        parts.append(f"default `{json.dumps(schema['default'])}`")
    return ", ".join(parts)


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def argument_rows(schema: dict, defs: dict, prefix: str = "") -> list:
    rows = []
    required = set(schema.get("required", []))
    for name, sub in schema.get("properties", {}).items():
        label = f"`{prefix}{name}`" + (" (required)" if name in required else "")
        notes = "; ".join(part for part in (cell(sub.get("description", "")), constraints(sub)) if part)
        rows.append(f"| {label} | {type_of(sub, defs)} | {notes} |")
        if sub.get("type") == "object" and "properties" in sub:
            rows.extend(argument_rows(sub, defs, prefix=f"{prefix}{name}."))
    return rows


def render(tools: list, server: dict) -> str:
    lines = ["# MCP tool reference", "",
             "Generated by `tests/mcp/gen_tool_reference.py` from `tools/list` of "
             f"{server.get('title', 'OrcaSlicer')} {server.get('version', '')}. Do not edit by hand.", "",
             f"{len(tools)} tools. R = read-only, D = destructive, I = idempotent.", "",
             "| Tool | R | D | I | |", "|---|---|---|---|---|"]
    for tool in tools:
        notes = tool["annotations"]
        marks = ["x" if notes.get(key) else "" for key in ("readOnlyHint", "destructiveHint", "idempotentHint")]
        summary = tool["description"].split(". ")[0].rstrip(".") + "."
        lines.append(f"| [`{tool['name']}`](#{tool['name']}) | {marks[0]} | {marks[1]} | {marks[2]} | {cell(summary)} |")
    lines.append("")

    shared = {}
    for tool in tools:
        lines += [f"## {tool['name']}", "", tool["description"], ""]
        schema = tool["inputSchema"]
        defs = schema.get("$defs", {})
        shared.update(defs)
        rows = argument_rows(schema, defs)
        if rows:
            lines += ["| Argument | Type | |", "|---|---|---|"] + rows + [""]
        else:
            lines += ["No arguments.", ""]
    if shared:
        lines += ["## Shared types", ""]
        for name in sorted(shared):
            lines += [f"**{name}**", "", "```json", json.dumps(shared[name], indent=1), "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--name", default="dev")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    run_dir = Path(os.environ.get("ORCA_MCP_RUN_DIR") or Path(__file__).resolve().parent / "run")
    state_file = run_dir / f"{args.name}.instance.json"
    app = None
    if state_file.exists():
        state = json.loads(state_file.read_text(encoding="utf-8"))
        url, token = state["url"], state["token"]
    else:
        # The reference describes a normal run: no debug tools.
        app = OrcaApp(fresh_data_dir(Path(tempfile.mkdtemp(prefix="orca_mcp_ref_")), "data"), debug_tools=False).start()
        url, token = app.url, app.token
    try:
        client = McpClient(url, token).connect()
        tools = [tool for tool in client.list_tools() if not tool["name"].startswith("debug_")]
        text = render(tools, client.server_info or {})
    finally:
        if app is not None:
            app.stop()

    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current.replace("\r\n", "\n") != text:
            sys.exit(f"{TARGET} is out of date; run tests/mcp/gen_tool_reference.py")
        print("up to date")
        return
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET} ({len(tools)} tools)")


if __name__ == "__main__":
    main()
